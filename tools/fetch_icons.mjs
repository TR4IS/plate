// Downloads the Lucide icons the app uses (ISC licence) and writes them as one ES module.
//
// Usage: node tools/fetch_icons.mjs public/js/icons.js
// To use a new icon, add a line to ICONS (app name: lucide file name) and run this again.
import { writeFileSync } from 'node:fs';

const VERSION = '1.54.0';
const ICONS = {
  alert: 'triangle-alert',
  arrowUp: 'arrow-up',
  bed: 'bed',
  book: 'book-open',
  bulb: 'lightbulb',
  calendar: 'calendar',
  camera: 'camera',
  check: 'check',
  copy: 'copy',
  down: 'chevron-down',
  download: 'download',
  dumbbell: 'dumbbell',
  eye: 'eye',
  eyeOff: 'eye-off',
  flip: 'switch-camera',
  forward: 'arrow-right',
  hand: 'hand',
  history: 'history',
  image: 'image',
  info: 'info',
  keyboard: 'keyboard',
  left: 'chevron-left',
  list: 'list',
  logout: 'log-out',
  minus: 'minus',
  more: 'ellipsis',
  note: 'message-square-text',
  offline: 'wifi-off',
  palette: 'palette',
  pause: 'pause',
  pencil: 'pencil',
  play: 'play',
  plus: 'plus',
  refresh: 'refresh-cw',
  retake: 'rotate-ccw',
  right: 'chevron-right',
  ruler: 'ruler',
  scale: 'weight',
  search: 'search',
  settings: 'settings',
  skip: 'skip-forward',
  sparkles: 'sparkles',
  squarePlus: 'square-plus',
  sun: 'sun',
  swap: 'arrow-left-right',
  target: 'target',
  timer: 'timer',
  today: 'house',
  trash: 'trash-2',
  trophy: 'trophy',
  undo: 'undo-2',
  up: 'chevron-up',
  user: 'user',
  users: 'users',
  utensils: 'utensils',
  x: 'x',
  zap: 'zap',
};

const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${file}.svg`);
  if (!res.ok) throw new Error(`Lucide has no icon called "${file}" (HTTP ${res.status})`);
  out[name] = (await res.text())
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>')
    .trim();
}

const lines = Object.entries(out).map(([name, markup]) => `  ${name}: ${JSON.stringify(markup)},`);
writeFileSync(
  process.argv[2],
  `// Icons from Lucide (https://lucide.dev) v${VERSION}, ISC licence (vendor/lucide.LICENSE).
// Generated by tools/fetch_icons.mjs - add an icon there and re-run it rather than editing this file.
// Each value is the inner markup of a 24x24 stroke icon.
export const ICONS = {
${lines.join('\n')}
};
`,
);
console.log(`wrote ${lines.length} icons to ${process.argv[2]}`);
